  final String languageCode;

  String t(String key, [Map<String, Object> values = const {}]) {
    var result =
        (_values[languageCode] ?? _values['zh']!)[key] ??
        _values['zh']![key] ??
        key;
    for (final entry in values.entries) {
      result = result.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return result;
  }

