  final String languageCode;

  String t(String key, [Map<String, Object> values = const {}]) {
    var result =
        (_values[languageCode] ?? _values['zh']!)[key] ??
        _values['zh']![key] ??
        key;
    for (final entry in values.entries) {
      result = result.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return result;
  }

  String lessonTitle(String id) => t('${id}Title');

  String lessonDetail(String id) => t('${id}Detail');

  String lessonDuration(String id) => t('${id}Duration');

  String lessonInstruction(String id) => t('${id}Instruction');

  String lessonGuidance(String id) => t('${id}Guidance');

  String songTitle(String id, String fallback) {
    final key = 'song_${id}_title';
    final value = t(key);
    return value == key ? fallback : value;
  }

